scan_shell_history() {
  section "Shell history"
  local h
  for h in "${HOME}/.zsh_history" "${HOME}/.bash_history"; do
    if [ -f "${h}" ]; then
      printf '  %s: %s lines, %s\n' "$(basename "${h}")" \
        "$(wc -l < "${h}" | tr -d ' ')" \
        "$(du -h "${h}" | awk '{print $1}')"
    fi
  done
}

# --- Commands -----------------------------------------------------------------
cmd_scan() {
  while [ $# -gt 0 ]; do
    case "$1" in
      --) shift; break ;;
      -*) echo "unknown flag: $1" >&2; exit 1 ;;
      *)  break ;;
    esac
  done

  echo "Laptop migration scan — $(date)"
  echo "Host: $(hostname)   User: ${USER}   macOS: $(sw_vers -productVersion 2>/dev/null || echo unknown)"

  scan_brew
  scan_mas
  if [ -n "${MAC_SETUP_ROOT}" ]; then
    scan_brewfile_delta "${MAC_SETUP_ROOT}/Brewfile"
  fi
  scan_ssh_keys
  scan_gpg_keys
  scan_cloud_auth
  scan_workspaces
  scan_repo_issues
  scan_vscode
  scan_jetbrains
  scan_fonts
  scan_launchagents
  scan_shell_history

  echo
  echo "Scan complete. Nothing was written. Review and then run 'export'."
}

# Build the list of real files to tar. Writes to a passed-in file list path.
build_file_list() {
  local listfile="$1" entry key self_rel

  # Script itself (so one scp'd tarball carries the install tool). Compute
  # the $HOME-relative path with pure bash string ops — avoids a python3
  # dependency that would trigger macOS's Command Line Tools install dialog
  # on a laptop where CLT hasn't been installed yet.
  self_rel=""
  case "${SCRIPT_PATH}" in
    "${HOME}/"*) self_rel="${SCRIPT_PATH#"${HOME}/"}" ;;
  esac
  if [ -n "${self_rel}" ] && [ -e "${HOME}/${self_rel}" ]; then
    printf '%s\n' "${self_rel}" >> "${listfile}"
  fi

  for entry in "${TRAVEL_PATHS[@]}"; do
    if [ -e "${HOME}/${entry}" ]; then
      printf '%s\n' "${entry}" >> "${listfile}"
    fi
  done

  # SSH private + public keys by glob. Both globs can match the same file
  # (`id_rsa.pub` matches `id_*` AND `*.pub`) so dedup before writing.
  {
    for key in "${HOME}/.ssh"/id_* "${HOME}/.ssh"/*.pub; do
      [ -f "${key}" ] || continue
      printf '%s\n' ".ssh/$(basename "${key}")"
    done
  } | sort -u >> "${listfile}"
}

# Describe (without executing) what stage_gpg_exports and stage_reports
# WOULD stage, for dry-run output. Purely read-only — no gpg/brew/mas/code
# invocations beyond `--list-keys` style metadata queries that don't
# prompt or write.
describe_staging() {
  local mac_setup="$1"
  if exists_cmd gpg; then
    local pub sec
    pub="$(gpg --list-keys --with-colons 2>/dev/null | awk -F: '$1=="pub"' | wc -l | tr -d ' ')"
    sec="$(gpg --list-secret-keys --with-colons 2>/dev/null | awk -F: '$1=="sec"' | wc -l | tr -d ' ')"
    if [ "${pub:-0}" -gt 0 ] || [ "${sec:-0}" -gt 0 ]; then
      echo "  gpg/public-keys.asc    (${pub} public key(s))"
      [ "${sec:-0}" -gt 0 ] && echo "  gpg/secret-keys.asc    (${sec} secret key(s))"
      echo "  gpg/ownertrust.txt     (if trust db has entries)"
    else
      echo "  gpg/                   (none — no keys in ring)"
    fi
  else
    echo "  gpg/                   (gpg not installed; skipped)"
  fi
  exists_cmd brew && echo "  reports/brew-leaves.txt, reports/brew-casks.txt"
  exists_cmd mas  && echo "  reports/mas-list.txt"
  exists_cmd code && echo "  reports/vscode-extensions.txt"
  [ -d "${HOME}/Library/Application Support/JetBrains" ] && echo "  reports/jetbrains-apps.txt"
  [ -d "${HOME}/Library/Fonts" ]                         && echo "  reports/fonts.txt"
  [ -d "${HOME}/Library/LaunchAgents" ]                  && echo "  reports/launchagents.txt"
  if [ -d "${HOME}/workspaces" ]; then
    echo "  reports/workspaces.tsv"
    echo "  reports/at-risk-repos.tsv"
  fi
  if [ -n "${mac_setup}" ] && [ -f "${mac_setup}/Brewfile" ] && exists_cmd brew; then
    echo "  reports/brewfile-delta.txt"
  fi
}

# Stage GPG exports into a tmp dir. Checks the keyring first so we don't
# invoke `--export-secret-keys` when there's nothing to export (which would
# otherwise prompt pinentry on some agent configs). Loud warnings if an
# export was expected but produced nothing — avoids silent "0-byte file
# deleted" failures that ship bundles without GPG material.
stage_gpg_exports() {
  local stage="$1"
  if ! exists_cmd gpg; then
    return 0
  fi
  mkdir -p "${stage}/gpg"

  local pub_count sec_count
  pub_count="$(gpg --list-keys --with-colons 2>/dev/null | awk -F: '$1=="pub"' | wc -l | tr -d ' ')"
  sec_count="$(gpg --list-secret-keys --with-colons 2>/dev/null | awk -F: '$1=="sec"' | wc -l | tr -d ' ')"

  if [ "${pub_count:-0}" -gt 0 ]; then
    if ! gpg --export --armor > "${stage}/gpg/public-keys.asc" 2>/dev/null; then
      echo "warn: gpg --export failed; public keys not bundled" >&2
      rm -f "${stage}/gpg/public-keys.asc"
    elif [ ! -s "${stage}/gpg/public-keys.asc" ]; then
      echo "warn: gpg --export produced empty output despite ${pub_count} key(s) in ring" >&2
      rm -f "${stage}/gpg/public-keys.asc"
    fi
  fi

  if [ "${sec_count:-0}" -gt 0 ]; then
    if ! gpg --export-secret-keys --armor > "${stage}/gpg/secret-keys.asc" 2>/dev/null; then
      echo "warn: gpg --export-secret-keys failed (pinentry cancelled?); secret keys NOT bundled" >&2
      rm -f "${stage}/gpg/secret-keys.asc"
    elif [ ! -s "${stage}/gpg/secret-keys.asc" ]; then
      echo "warn: gpg --export-secret-keys produced empty output despite ${sec_count} key(s) in ring" >&2
      rm -f "${stage}/gpg/secret-keys.asc"
    fi
  fi

  # Ownertrust is always safe to export; empty output is normal when no
  # explicit trust is set, so no warning on empty.
  gpg --export-ownertrust > "${stage}/gpg/ownertrust.txt" 2>/dev/null || true
  [ -s "${stage}/gpg/ownertrust.txt" ] || rm -f "${stage}/gpg/ownertrust.txt"
}

# Build the reports (plaintext checklists) into a tmp dir.
stage_reports() {
  local stage="$1" mac_setup="$2"
  mkdir -p "${stage}/reports"
  if exists_cmd brew; then
    brew leaves          > "${stage}/reports/brew-leaves.txt" 2>/dev/null || true
    brew list --cask     > "${stage}/reports/brew-casks.txt"  2>/dev/null || true
  fi
  if exists_cmd mas; then
    mas list             > "${stage}/reports/mas-list.txt"    2>/dev/null || true
  fi
  if exists_cmd code; then
    code --list-extensions > "${stage}/reports/vscode-extensions.txt" 2>/dev/null || true
  fi
  local jb="${HOME}/Library/Application Support/JetBrains"
  [ -d "${jb}" ] && ls -1 "${jb}" > "${stage}/reports/jetbrains-apps.txt" 2>/dev/null || true
  local fonts="${HOME}/Library/Fonts"
  [ -d "${fonts}" ] && ls -1 "${fonts}" > "${stage}/reports/fonts.txt" 2>/dev/null || true
  local la="${HOME}/Library/LaunchAgents"
  [ -d "${la}" ] && ls -1 "${la}" > "${stage}/reports/launchagents.txt" 2>/dev/null || true

  # Workspaces inventory.
  local ws="${HOME}/workspaces" repo origin branch rel labels
  if [ -d "${ws}" ]; then
    {
      printf 'PATH\tBRANCH\tORIGIN\n'
      find "${ws}" -maxdepth 4 -type d -name .git 2>/dev/null | while read -r g; do
        repo="$(dirname "${g}")"
        origin="$(git -C "${repo}" remote get-url origin 2>/dev/null || echo '-')"
        branch="$(git -C "${repo}" rev-parse --abbrev-ref HEAD 2>/dev/null || echo '-')"
        rel="${repo#"${HOME}"/}"
        printf '%s\t%s\t%s\n' "${rel}" "${branch}" "${origin}"
      done
    } > "${stage}/reports/workspaces.tsv"

    # Repos with work a fresh clone would lose. Only populated with rows for
    # repos that actually need attention — a clean list stays empty + header.
    {
      printf 'PATH\tSTATUS\n'
      while IFS= read -r g; do
        repo="$(dirname "${g}")"
        if labels="$(repo_status_label "${repo}")"; then
          rel="${repo#"${HOME}"/}"
          printf '%s\t%s\n' "${rel}" "${labels}"
        fi
      done < <(find "${ws}" -maxdepth 4 -type d -name .git 2>/dev/null)
    } > "${stage}/reports/at-risk-repos.tsv"
  fi

  if [ -n "${mac_setup}" ] && [ -f "${mac_setup}/Brewfile" ] && exists_cmd brew; then
    scan_brewfile_delta "${mac_setup}/Brewfile" > "${stage}/reports/brewfile-delta.txt" 2>/dev/null || true
  fi

  find "${stage}/reports" -type f -empty -delete 2>/dev/null || true
}

cmd_export() {
  local assume_yes=0 encrypt=0 dry_run=0
  while [ $# -gt 0 ]; do
    case "$1" in
      --dry-run)   dry_run=1; shift ;;
      --yes|-y)    assume_yes=1; shift ;;
      --encrypt)   encrypt=1; shift ;;
      --)          shift; break ;;
      -*)          echo "unknown flag: $1" >&2; exit 1 ;;
      *)           break ;;
    esac
  done

  if [ "${encrypt}" -eq 1 ]; then
    require_gpg || exit 1
  fi

  local base_outfile="${1:-${HOME}/laptop-migration-$(date +%Y%m%d-%H%M%S).tar.gz}"
  local outfile="${base_outfile}"
  [ "${encrypt}" -eq 1 ] && outfile="${base_outfile}.gpg"

  # Stage dynamic contents (GPG exports, reports) under a tmp root that
  # mirrors $HOME, then tar from both $HOME and the stage root.
  local stage listfile
  stage="$(mktemp -d -t laptop-mig-XXXXXX)"
  # The listfile sits OUTSIDE the stage dir so tar's `-C stage .` doesn't
  # scoop it up as a bundle member.
  listfile="$(mktemp -t laptop-mig-filelist-XXXXXX)"
  # Expand at trap-setup time: both locals go out of scope before the
  # top-level EXIT fires. Embedding the literal paths now keeps cleanup
  # correct even after the function returns.
  # shellcheck disable=SC2064
  trap "rm -rf '${stage}' '${listfile}'" EXIT

  # build_file_list is read-only — walks $HOME, no exec of gpg/brew/etc.
  # The actual gpg exports and reports generation is deferred until past the
  # dry-run short-circuit so `--dry-run` doesn't invoke gpg (which would
  # otherwise prompt pinentry on users with secret keys) or shell out to
  # brew/mas/code during what should be a pure audit.
  build_file_list "${listfile}"

  if [ ! -s "${listfile}" ]; then
    echo "error: nothing to export from \$HOME" >&2
    exit 1
  fi

  local verb="Bundling"
  [ "${dry_run}" -eq 1 ] && verb="Would bundle"
  echo "${verb} the following paths (relative to \$HOME):"
  while IFS= read -r rel; do
    [ -n "${rel}" ] || continue
    local sz
    sz="$(du -sh "${HOME}/${rel}" 2>/dev/null | awk '{print $1}')"
    printf '  %-6s  %s\n' "${sz:--}" "${rel}"
  done < "${listfile}"
  echo

  if [ "${dry_run}" -eq 1 ]; then
    echo "Would also include (not invoked during dry-run — these are read-only"
    echo "estimates based on what's installed; size not counted below):"
    describe_staging "${MAC_SETUP_ROOT}"
    echo

    local approx_kb=0 n rel
    while IFS= read -r rel; do
      [ -n "${rel}" ] || continue
      n="$(du -sk -L "${HOME}/${rel}" 2>/dev/null | awk '{print $1}')"
      [ -n "${n}" ] && approx_kb=$((approx_kb + n))
    done < "${listfile}"
    local approx_h
    approx_h="$(awk -v k="${approx_kb}" \
      'BEGIN { split("K M G T", u); i=1; while (k>=1024 && i<4) { k/=1024; i++ } printf "%.1f%s", k, u[i] }')"
    echo "Dry run — nothing was written. No gpg or brew/mas commands invoked."
    echo "  pre-compression size: ~${approx_h} (\$HOME paths only; staged exports"
    echo "                        and reports add on the order of hundreds of KB)"
    echo "  encryption:           $([ "${encrypt}" -eq 1 ] && echo "would wrap through gpg -c (AES-256)" || echo "disabled")"
    echo "  would write:          ${outfile}"
    echo "  would write:          ${outfile}.sha256"
    return 0
  fi

  # From here on this is the real run. Stage GPG material + reports now
  # (not before dry-run — see note above).
  stage_gpg_exports "${stage}"
  stage_reports     "${stage}" "${MAC_SETUP_ROOT}"

  echo "Plus staged artifacts (not in \$HOME, extracted to the bundle root):"
  (cd "${stage}" && find gpg reports -type f 2>/dev/null | while read -r f; do
    local sz2
    sz2="$(du -sh "${f}" 2>/dev/null | awk '{print $1}')"
    printf '  %-6s  %s\n' "${sz2:--}" "${f}"
  done)
  echo

  if [ "${assume_yes}" -ne 1 ]; then
    printf 'Proceed? [y/N] '
    local answer=""
    if ! read -r answer; then answer=""; fi
    case "${answer}" in
      y|Y|yes|YES) : ;;
      *) echo "Aborted."; exit 1 ;;
    esac
  fi

  # Stage every $HOME-rooted path under ${stage}/ at its original relative
  # path. BSD tar (macOS default) can't mix `-T listfile` with `-C` the way
  # GNU tar does — once file args start, `-T` is treated as a filename. By
  # mirroring the $HOME paths into the stage dir, we get one source tree
  # and the archive layout is identical to the earlier design: $HOME paths
  # at the top, `gpg/` and `reports/` next to them.
  local rel
  while IFS= read -r rel; do
    [ -n "${rel}" ] || continue
    mkdir -p "${stage}/$(dirname "${rel}")"
    cp -a "${HOME}/${rel}" "${stage}/${rel}"
  done < "${listfile}"

  if [ "${encrypt}" -eq 1 ]; then
    echo "Encrypting with GPG symmetric (AES-256). Prompted for passphrase twice."
    echo "Store it in a password manager — a lost passphrase makes the bundle"
    echo "unrecoverable."
    echo
    tar -czf - -C "${stage}" . \
      | gpg --symmetric --cipher-algo AES256 --output "${outfile}"
  else
    tar -czf "${outfile}" -C "${stage}" .
  fi

  local sumfile size
  sumfile="$(write_sha256 "${outfile}")"
  size="$(du -h "${outfile}" | awk '{print $1}')"
  echo "Wrote ${outfile} (${size})."
  echo "Wrote ${sumfile}"
  echo
  echo "Copy both files to the new laptop (same directory), then:"
  echo "  ./migrate-laptop.sh install --dry-run \"$(basename "${outfile}")\""
  echo "  ./migrate-laptop.sh install \"$(basename "${outfile}")\""
}

# Apply correct POSIX perms to key material after extraction. Only touches
# paths this script actually transfers — leaves pre-existing files on the
# new laptop alone.
fix_perms() {
  if [ -d "${HOME}/.ssh" ]; then
    chmod 0700 "${HOME}/.ssh" || true
    find "${HOME}/.ssh" -maxdepth 1 -type f -name 'id_*' ! -name '*.pub' \
      -exec chmod 0600 {} \; 2>/dev/null || true
    find "${HOME}/.ssh" -maxdepth 1 -type f \
      \( -name 'config' -o -name 'known_hosts' -o -name 'authorized_keys' -o -name '*.pub' \) \
      -exec chmod 0644 {} \; 2>/dev/null || true
  fi
}

# Import staged GPG material if present. Failures are loud rather than
# silent — a swallowed import error means the user discovers signing is
# broken days later, by which time this script's state is long gone.
import_gpg() {
  local root="$1"
  [ -d "${root}/gpg" ] || return 0
  if ! exists_cmd gpg; then
    echo "  gpg not installed yet — install it then re-run:"
    echo "    gpg --import ${root}/gpg/secret-keys.asc"
    echo "    gpg --import-ownertrust ${root}/gpg/ownertrust.txt"
    return 0
  fi
  local fail=0
  if [ -f "${root}/gpg/secret-keys.asc" ]; then
    echo "  gpg --import ${root}/gpg/secret-keys.asc"
    if ! gpg --import "${root}/gpg/secret-keys.asc" 2>&1 | sed 's/^/    /'; then
      echo "  [FAIL] gpg --import secret-keys.asc returned non-zero" >&2
      fail=1
    fi
  fi
  if [ -f "${root}/gpg/public-keys.asc" ]; then
    if ! gpg --import "${root}/gpg/public-keys.asc" 2>/dev/null; then
      echo "  [warn] gpg --import public-keys.asc returned non-zero" >&2
    fi
  fi
  if [ -f "${root}/gpg/ownertrust.txt" ]; then
    echo "  gpg --import-ownertrust ${root}/gpg/ownertrust.txt"
    if ! gpg --import-ownertrust "${root}/gpg/ownertrust.txt" 2>&1 | sed 's/^/    /'; then
      echo "  [FAIL] gpg --import-ownertrust returned non-zero" >&2
      fail=1
    fi
  fi
  if [ "${fail}" -ne 0 ]; then
    echo "  --> GPG import had failures. Address them before relying on signing." >&2
  fi
  return 0
}

# Copy extracted $HOME-rooted paths into the real $HOME, backing up each
# collision to a .backup-STAMP sibling. The staged `gpg/` and `reports/`
# subtrees are NOT merged into $HOME; they are left under the extract root
# for the user to consult and import.
place_files() {
  local root="$1" stamp="$2" rel src dst
  cd "${root}" || { echo "error: cannot cd into extract root ${root}" >&2; return 1; }
  # Everything except gpg/ and reports/ represents a $HOME-rooted path.
  find . -mindepth 1 -maxdepth 1 \
    ! -name gpg ! -name reports ! -name 'migrate-laptop.sh' \
    -print 2>/dev/null | while read -r rel; do
    rel="${rel#./}"
    src="${root}/${rel}"
    dst="${HOME}/${rel}"
    if [ -e "${dst}" ]; then
      local backup="${dst}.backup-${stamp}"
      echo "  backup: ${dst} -> ${backup}"
      # Rename dst to the backup path. Atomic on the same filesystem, and
      # avoids BSD `cp -a src_dir dst_dir` nesting the source INSIDE an
      # existing destination (which would land SSH keys at
      # `~/.ssh/.ssh/id_rsa`). The backup preserves prior contents; the
      # subsequent `cp -a` then creates a fresh dst from the extracted
      # archive. No `rm` touches live state.
      mv "${dst}" "${backup}"
    else
      mkdir -p "$(dirname "${dst}")"
    fi
    echo "  place:  ${rel}"
    cp -a "${src}" "${dst}"
  done
}

cmd_install() {
  local dry_run=0
  while [ $# -gt 0 ]; do
    case "$1" in
      --dry-run) dry_run=1; shift ;;
      --)        shift; break ;;
      -*)        echo "unknown flag: $1" >&2; exit 1 ;;
      *)         break ;;
    esac
  done

  local tarball="${1:-}"
  if [ -z "${tarball}" ] || [ ! -f "${tarball}" ]; then
    echo "error: pass a tarball produced by 'export'" >&2
    exit 1
  fi

  verify_sha256 "${tarball}" || { echo "integrity check failed — refusing to extract" >&2; exit 1; }

  if is_encrypted_tarball "${tarball}"; then
    require_gpg || exit 1
    echo "Tarball is encrypted. GPG will prompt for the passphrase."
  fi

  local tmp
  tmp="$(mktemp -d -t laptop-install-XXXXXX)"
  # Expand at trap-setup time (see note in cmd_export).
  # shellcheck disable=SC2064
  trap "rm -rf '${tmp}'" EXIT

  echo "Extracting to ${tmp}"
  extract_tarball "${tarball}" "${tmp}"
  echo

  if [ "${dry_run}" -eq 1 ]; then
    echo "Dry-run contents:"
    (cd "${tmp}" && find . -maxdepth 3 -print) | sed 's/^/  /'
    echo
    cmd_verify --root "${tmp}"
    echo
    echo "Dry-run complete. Nothing under ${HOME} was modified."
    return 0
  fi

  local stamp
  stamp="$(date +%Y%m%d-%H%M%S)"

  echo "Placing files into \$HOME (collisions backed up to .backup-${stamp}):"
  place_files "${tmp}" "${stamp}"
  echo

  echo "Fixing permissions on key material..."
  fix_perms
  echo

  echo "Importing GPG material (if present):"
  import_gpg "${tmp}"
  echo

  cmd_verify

  echo
  echo "Reports (checklists for the manual-step phase) are at:"
  (cd "${tmp}" && find reports -type f 2>/dev/null | sed 's/^/  /') || true
  echo
  echo "Next steps on this laptop:"
  cat <<'EOF'
  1. Regenerate auth this script deliberately did not transfer:
       aws configure sso / aws sso login
       gh auth login
       docker login <registry>   (per registry)
       <org CLI> for internal AWS / Kubernetes / package-registry auth
  2. Re-clone workspace repos listed in reports/workspaces.tsv.
  3. Walk reports/brewfile-delta.txt — move anything worth keeping into
     the Brewfile (public) or Brewfile.local (private), then re-run
     mac-setup to install.
  4. Walk reports/vscode-extensions.txt and reports/jetbrains-apps.txt
     against your IDE Settings Sync; install anything missing.
  5. Manual sign-ins the script cannot carry:
       - 1Password (unlock, verify SSH agent)
       - iCloud / Apple ID (Messages, Photos, Keychain restore)
       - Browser profiles (Chrome / Firefox / Arc sync)
       - Any SSO not scripted by your org CLI
       - Time Machine first backup
  6. Finally: ./migrate-claude-code.sh restore <claude-tarball>
EOF
}

cmd_verify() {
  local root="${HOME}"
  while [ $# -gt 0 ]; do
    case "$1" in
      --root) root="$2"; shift 2 ;;
      --)     shift; break ;;
      -*)     echo "unknown flag: $1" >&2; return 1 ;;
      *)      break ;;
    esac
  done

  local ok=0 miss=0 note=0
  check() {
    local label="$1" path="$2" required="${3:-optional}"
    if [ -e "${path}" ]; then
      printf '  [ok]   %s\n' "${label}"
      ok=$((ok + 1))
    elif [ "${required}" = "required" ]; then
      printf '  [MISS] %s  (expected %s)\n' "${label}" "${path}"
      miss=$((miss + 1))
    else
      printf '  [--]   %s  (not present — ok if source laptop had none)\n' "${label}"
      note=$((note + 1))
    fi
  }

  echo "Checking installed state under ${root}:"
  check "SSH config"           "${root}/.ssh/config"              optional
  check "SSH known_hosts"      "${root}/.ssh/known_hosts"         optional
  check "zsh history"          "${root}/.zsh_history"             optional
  check "gitconfig.local"      "${root}/.gitconfig.local"         optional

  # If we're verifying an extract staging dir, also note staged content.
  if [ "${root}" != "${HOME}" ]; then
    echo
    echo "Staged artifacts in the extract root:"
    [ -d "${root}/gpg" ]     && ls -1 "${root}/gpg"     | sed 's/^/  gpg\//'     || echo "  (no gpg/)"
    [ -d "${root}/reports" ] && ls -1 "${root}/reports" | sed 's/^/  reports\//' || echo "  (no reports/)"
  fi

  echo
  echo "Verification: ${ok} present, ${note} absent (optional), ${miss} missing (required)."
  [ "${miss}" -eq 0 ]
}

# Print the file's header comment block (everything above `set -euo pipefail`),
# so the help text can grow without having to update line numbers here.
print_help() {
  awk 'NR==1 { next } /^set / { exit } { sub(/^# ?/, ""); print }' "$0"
}

case "${1:-}" in
  scan)     shift; cmd_scan "$@" ;;
  export)   shift; cmd_export "$@" ;;
  install)  shift; cmd_install "$@" ;;
  verify)   shift; cmd_verify "$@" ;;
  -h|--help|help|"") print_help; exit 0 ;;
  *) echo "unknown command: $1" >&2; print_help; exit 1 ;;
esac

#!/usr/bin/env bash
# Migrate a personal macOS workstation to a new laptop.
#
# This is the "carry the gap" script. It pairs with two other tools:
#
#   pjungermann/mac-setup               Desired-state installer (Homebrew,
#                                       chezmoi dotfiles, mise runtimes,
#                                       shell). Run FIRST on the new laptop.
#   ./mac-setup.sh migrate-claude-code  Claude Code memory, history, plugins.
#                                       Run AFTER this script.
#
# This script carries what the other two don't: secrets, per-tool auth
# tokens, SSH / GPG keys, shell history, and an inventory of your current
# workspace so you can re-clone the repos you were actually using. If a
# thing can be re-declared in the Brewfile or a chezmoi template, put it
# THERE, not here.
#
# Usage:
#   ./mac-setup.sh migrate-laptop scan                                 # read-only report
#   ./mac-setup.sh migrate-laptop export [--dry-run] [--yes] [--encrypt] [outfile]
#   ./mac-setup.sh migrate-laptop install [--dry-run] <tarball>
#   ./mac-setup.sh migrate-laptop verify [--root <path>]
#   ./mac-setup.sh migrate-laptop --help
#
# Direct invocation as `bin/migrate-laptop.sh <command> ...` works too; the
# router form above is the one the README documents.
#
# Encryption (recommended, this bundle carries real secrets):
#   `export --encrypt` streams the tar through `gpg -c` (AES-256 symmetric)
#   and writes <tarball>.gpg instead of a plain tarball. The plaintext tar
#   never touches disk. GPG prompts for a passphrase twice. `install`
#   auto-detects the `.gpg` suffix. Requires `gpg` on PATH
#   (macOS: `brew install gnupg`). Store the passphrase in a password
#   manager. A lost passphrase makes the tarball unrecoverable.
#
# End-to-end workflow:
#
#   1. On the OLD laptop, audit first; no files written.
#      ./mac-setup.sh migrate-laptop scan
#
#   2. Bundle. Writes two files beside each other:
#        ~/laptop-migration-YYYYMMDD-HHMMSS.tar.gz(.gpg)
#        ~/laptop-migration-YYYYMMDD-HHMMSS.tar.gz(.gpg).sha256
#      ./mac-setup.sh migrate-laptop export --encrypt
#
#   3. Copy BOTH files to the new laptop (encrypted bundle recommended):
#      scp ~/laptop-migration-*.tar.gz.gpg*   newlaptop:~/
#
#   4. On the NEW laptop, run mac-setup FIRST so brew + shell exist.
#      Then pull this script out of the tarball and dry-run. Steps 4-5
#      use the direct `./bin/migrate-laptop.sh` form because the tarball
#      ships only this one script, not the full repo clone; use the
#      `./mac-setup.sh migrate-laptop ...` router form once the clone is
#      in place. The tarball member key is the path the source machine
#      invoked the script from (for a repo clone, likely
#      `bin/migrate-laptop.sh`). List it first to confirm, then extract
#      using that exact path:
#        gpg --decrypt laptop-migration-*.tar.gz.gpg | tar -tzf - | grep migrate-laptop
#        gpg --decrypt laptop-migration-*.tar.gz.gpg \
#          | tar -xzf - bin/migrate-laptop.sh
#        ./bin/migrate-laptop.sh install --dry-run laptop-migration-*.tar.gz.gpg
#
#   5. If the dry-run looks right, install for real. Existing files that
#      would be overwritten are first copied to a .backup-YYYYMMDD-HHMMSS
#      sibling path.
#      ./bin/migrate-laptop.sh install laptop-migration-*.tar.gz.gpg
#
#   6. Then run `./mac-setup.sh migrate-claude-code restore <tarball>`
#      and walk the printed manual-steps checklist (1Password, iCloud,
#      SSO, browser sign-ins, IDE Settings Sync, Time Machine, iMessage).
#
# What travels (each category exported only if present on the source laptop):
#   SSH:         ~/.ssh/{config,known_hosts,authorized_keys,id_*,id_*.pub}
#   GPG:         staged exports via `gpg --export`, `--export-secret-keys`,
#                `--export-ownertrust`. NOT the live ~/.gnupg sockets.
#   Shell/git:   ~/.zsh_history, ~/.bash_history, ~/.gitconfig.local,
#                ~/.zshrc.local, ~/.zshenv.local, ~/.zprofile.local
#   Reports:     reports/brew-leaves.txt, reports/brew-casks.txt,
#                reports/mas-list.txt, reports/vscode-extensions.txt,
#                reports/jetbrains-apps.txt, reports/workspaces.tsv,
#                reports/fonts.txt, reports/launchagents.txt,
#                reports/brewfile-delta.txt (if the mac-setup clone this
#                script runs from has a Brewfile)
#
# What explicitly does NOT travel (and why):
#   ~/.claude/              `./mac-setup.sh migrate-claude-code` owns this.
#   ~/.aws/                 Regenerated by your SSO flow (aws configure sso,
#                           aws sso login, saml2aws, or an org-specific CLI).
#   ~/.kube/                Rebuilt by your cluster auth tooling (aws eks
#                           update-kubeconfig or an org-specific CLI);
#                           mostly ~/.kube/cache noise anyway.
#   ~/.docker/config.json   `docker login <registry>` regenerates it;
#                           ECR auth is typically scripted by an org CLI.
#   ~/.config/gh/           `gh auth login` (device flow, 30s).
#   ~/.config/op/           1Password desktop + `op signin`.
#   ~/.npmrc, ~/.yarnrc*    registry tokens (CodeArtifact, GitHub Packages,
#                           etc.) are refreshed by their respective CLIs;
#                           non-token settings have been empty on inspection.
#   ~/.cargo/credentials.toml  `cargo login` on the rare case it is needed.
#   ~/.netrc, ~/.pgpass     per-service re-add; not in use on current laptop.
#   Brewfile-managed state  mac-setup reinstalls it from the Brewfile.
#   chezmoi-managed dotfiles  mac-setup lays them down fresh.
#   Browser profiles        Use the browser's own sync (Chrome / Firefox / Arc).
#   Keychain, Messages, Photos  iCloud restores these.
#   node_modules, .venv, caches, build artifacts  Regenerable.
#   Workspace repos themselves  reports/workspaces.tsv lists them; re-clone.
#   MDM-pushed app state    IT handles reprovisioning.
#
# Session transcripts and token files can contain anything you or any
# tool authenticated against. Treat the resulting tarball accordingly:
# use --encrypt, don't leave it on shared storage, delete after install.

set -euo pipefail

SCRIPT_PATH="$(cd "$(dirname "$0")" && pwd)/$(basename "$0")"

# Repo root of the mac-setup clone this script lives in. Used only to locate
# a Brewfile for the brew-delta report. Set to the empty string when the
# script is not running from inside a mac-setup clone (e.g. extracted from
# a bundle on a bare laptop, or symlinked out of its home), so the delta
# section is quietly skipped. The `mac-setup.sh` sibling check guards
# against a symlinked script picking up an unrelated Brewfile that happens
# to sit at the inferred parent dir.
_mac_setup_candidate="$(cd "$(dirname "${SCRIPT_PATH}")/.." && pwd -P)"
if [ -f "${_mac_setup_candidate}/Brewfile" ] \
   && [ -f "${_mac_setup_candidate}/mac-setup.sh" ]; then
  MAC_SETUP_ROOT="${_mac_setup_candidate}"
else
  MAC_SETUP_ROOT=""
fi
unset _mac_setup_candidate

# --- Catalog ------------------------------------------------------------------
# Paths under $HOME that travel verbatim (file or dir). Only entries that
# actually exist are included at export time.
#
# Design rule: a path belongs here only if its *contents* cost real time to
# recreate. Token files recreated by a short re-login flow (`gh auth login`,
# `docker login`, `op signin`, `cargo login`, package-registry CLIs)
# are deliberately NOT listed — carrying them is extra attack surface
# without saving meaningful setup time.
TRAVEL_PATHS=(
  ".ssh/config"
  ".ssh/known_hosts"
  ".ssh/authorized_keys"
  ".zsh_history"
  ".bash_history"
  ".gitconfig.local"
  ".zshrc.local"
  ".zshenv.local"
  ".zprofile.local"
)

# .ssh key material is picked up via glob at export time (id_*, *.pub) so
# we don't need to enumerate every algorithm.
#
# Paths deliberately NOT bundled are documented in the header comment
# ("What explicitly does NOT travel") — not duplicated here.

# --- SHA256 / encryption helpers (same shape as migrate-claude-code.sh) ------
sha256_tool() {
  if command -v shasum >/dev/null 2>&1; then
    echo "shasum"
  elif command -v sha256sum >/dev/null 2>&1; then
    echo "sha256sum"
  else
    return 1
  fi
}

write_sha256() {
  local file="$1"
  local sumfile="${file}.sha256"
  (cd "$(dirname "${file}")" && {
    if command -v shasum >/dev/null 2>&1; then
      shasum -a 256 "$(basename "${file}")"
    else
      sha256sum "$(basename "${file}")"
    fi
  }) > "${sumfile}"
  echo "${sumfile}"
}

verify_sha256() {
  local file="$1"
  local sumfile="${file}.sha256"
  if [ ! -f "${sumfile}" ]; then
    echo "error: no ${sumfile##*/} alongside tarball; refusing to install" >&2
    echo "  install is fail-closed on integrity. Regenerate the sidecar with:" >&2
    echo "    shasum -a 256 \"$(basename "${file}")\" > \"$(basename "${sumfile}")\"" >&2
    echo "  (only safe if you trust the tarball — the whole point of the check)" >&2
    return 1
  fi
  echo "Verifying integrity against $(basename "${sumfile}")..."
  (cd "$(dirname "${file}")" && {
    if command -v shasum >/dev/null 2>&1; then
      shasum -a 256 -c "$(basename "${sumfile}")"
    else
      sha256sum -c "$(basename "${sumfile}")"
    fi
  })
}

is_encrypted_tarball() {
  case "$1" in
    *.gpg) return 0 ;;
    *)     return 1 ;;
  esac
}

require_gpg() {
  if ! command -v gpg >/dev/null 2>&1; then
    echo "error: this operation needs 'gpg' on PATH (macOS: 'brew install gnupg')" >&2
    return 1
  fi
}

extract_tarball() {
  local tarball="$1" dest="$2"
  if is_encrypted_tarball "${tarball}"; then
    require_gpg || return 1
    gpg --decrypt --quiet --output - "${tarball}" | tar -xzf - -C "${dest}"
  else
    tar -xzf "${tarball}" -C "${dest}"
  fi
}

# --- Scan helpers -------------------------------------------------------------
section() {
  echo
  echo "=== $1 ==="
}

exists_cmd() {
  command -v "$1" >/dev/null 2>&1
}

scan_brew() {
  section "Homebrew"
  if ! exists_cmd brew; then
    echo "  (brew not installed on this laptop)"
    return
  fi
  echo "-- leaves --"
  brew leaves 2>/dev/null | sed 's/^/  /'
  echo "-- casks --"
  brew list --cask 2>/dev/null | sed 's/^/  /'
}

scan_mas() {
  section "Mac App Store"
  if ! exists_cmd mas; then
    echo "  (mas not installed)"
    return
  fi
  mas list 2>/dev/null | sed 's/^/  /'
}

# Extract tool names from a mise config.toml. Strips backend prefixes
# (cargo:, npm:, pipx:, go:, etc.) so names compare cleanly against brew
# formula names.
mise_tool_names() {
  local toml="$1"
  [ -f "${toml}" ] || return 0
  awk '
    /^\[tools\]/ { in_tools=1; next }
    /^\[/        { in_tools=0 }
    in_tools && /=/ && !/^[[:space:]]*#/ {
      sub(/[[:space:]]*=.*/, "")
      gsub(/^[[:space:]]+|[[:space:]]+$/, "")
      gsub(/^"|"$/, "")
      sub(/^[a-z]+:/, "")
      if (length($0) > 0) print
    }
  ' "${toml}" | sort -u
}

scan_brewfile_delta() {
  local brewfile="$1"
  local mise_toml="${brewfile%/Brewfile}/dot_config/mise/config.toml"
  section "Brewfile / mise delta"
  if [ ! -f "${brewfile}" ]; then
    echo "  (no Brewfile at ${brewfile})"
    return
  fi
  if ! exists_cmd brew; then
    echo "  (brew not available; cannot compute delta)"
    return
  fi

  local installed_leaves installed_casks
  installed_leaves="$(brew leaves 2>/dev/null | sort -u)"
  installed_casks="$(brew list --cask 2>/dev/null | sort -u)"

  local brewfile_formulae brewfile_casks
  brewfile_formulae="$(awk '/^[[:space:]]*brew[[:space:]]+/ { gsub(/"/, "", $2); print $2 }' "${brewfile}" | sort -u)"
  brewfile_casks="$(awk '/^[[:space:]]*cask[[:space:]]+/ { gsub(/"/, "", $2); print $2 }' "${brewfile}" | sort -u)"

  local mise_tools=""
  if [ -f "${mise_toml}" ]; then
    mise_tools="$(mise_tool_names "${mise_toml}")"
  fi

  # Everything the desired state covers (either file).
  local tracked
  tracked="$(printf '%s\n%s\n' "${brewfile_formulae}" "${mise_tools}" | sort -u)"
  # Installed via brew and also tracked by mise -> duplication (brew uninstall).
  local duplication
  duplication="$(comm -12 <(printf '%s\n' "${installed_leaves}") <(printf '%s\n' "${mise_tools}"))"
  # Installed and not tracked anywhere -> real drift.
  local untracked
  untracked="$(comm -23 <(printf '%s\n' "${installed_leaves}") <(printf '%s\n' "${tracked}"))"

  echo "-- formulae: installed but not tracked by Brewfile or mise (real drift) --"
  if [ -n "${untracked}" ]; then
    printf '%s\n' "${untracked}" | sed 's/^/  /'
  else
    echo "  (none)"
  fi
  echo "-- formulae: brew-installed but mise-tracked (duplication — \`brew uninstall\` recommended) --"
  if [ -n "${duplication}" ]; then
    printf '%s\n' "${duplication}" | sed 's/^/  /'
  else
    echo "  (none)"
  fi
  if [ ! -f "${mise_toml}" ]; then
    echo "  (note: no mise config at ${mise_toml} — duplication check skipped)"
  fi
  echo "-- casks: installed on this laptop but missing from Brewfile --"
  comm -23 <(printf '%s\n' "${installed_casks}") <(printf '%s\n' "${brewfile_casks}") | sed 's/^/  /'
}

scan_ssh_keys() {
  section "SSH keys"
  local dir="${HOME}/.ssh" key
  if [ ! -d "${dir}" ]; then
    echo "  (no ~/.ssh directory)"
    return
  fi
  for key in "${dir}"/*.pub; do
    [ -f "${key}" ] || continue
    ssh-keygen -lf "${key}" 2>/dev/null | sed 's/^/  /'
  done
  echo "-- config present? --"
  [ -f "${dir}/config" ] && echo "  yes ($(wc -l < "${dir}/config" | tr -d ' ') lines)" || echo "  no"
  echo "-- known_hosts entries --"
  [ -f "${dir}/known_hosts" ] && echo "  $(wc -l < "${dir}/known_hosts" | tr -d ' ') hosts" || echo "  no known_hosts"
}

scan_gpg_keys() {
  section "GPG keys"
  if ! exists_cmd gpg; then
    echo "  (gpg not installed)"
    return
  fi
  echo "-- secret keys --"
  gpg --list-secret-keys --keyid-format long 2>/dev/null | sed 's/^/  /'
}

scan_cloud_auth() {
  section "Cloud / CLI auth to re-login on new laptop (NOT transferred)"
  local p
  for p in \
    ".aws/credentials" ".aws/config" \
    ".config/gcloud/credentials.db" ".config/gcloud/configurations" \
    ".kube/config" \
    ".docker/config.json" \
    ".config/gh/hosts.yml" \
    ".config/op"
  do
    if [ -e "${HOME}/${p}" ]; then
      # shellcheck disable=SC2088 # literal "~/..." for display, no expansion wanted
      printf '  [present on this laptop] %s\n' "~/${p}"
    fi
  done
}

scan_workspaces() {
  section "Workspace repos (~/workspaces)"
  local root="${HOME}/workspaces"
  if [ ! -d "${root}" ]; then
    echo "  (no ~/workspaces)"
    return
  fi
  printf '  %-40s  %-24s  %s\n' "PATH" "BRANCH" "ORIGIN"
  # Walk two levels deep by default; most layouts are ~/workspaces/<host>/<repo>
  local repo origin branch rel
  find "${root}" -maxdepth 4 -type d -name .git 2>/dev/null | while read -r g; do
    repo="$(dirname "${g}")"
    origin="$(git -C "${repo}" remote get-url origin 2>/dev/null || echo '-')"
    branch="$(git -C "${repo}" rev-parse --abbrev-ref HEAD 2>/dev/null || echo '-')"
    rel="${repo#"${HOME}"/}"
    printf '  %-40s  %-24s  %s\n' "${rel}" "${branch}" "${origin}"
  done
}

# Compute a short status label if a repo has work that a fresh clone would
# lose. Prints the label on stdout and returns 0 when there are issues;
# returns 1 when the repo is clean. Signals checked:
#   dirty(N)       -- uncommitted changes in the working tree
#   stash(N)       -- stashes present
#   ahead(N)       -- local branches with commits not pushed to upstream
#   local-only(N)  -- local branches that have no upstream at all
#   worktrees(N)   -- extra worktrees under .worktrees/ etc.
repo_status_label() {
  local repo="$1"
  local labels=() n upstream line _name

  n="$(git -C "${repo}" status --porcelain 2>/dev/null | wc -l | tr -d ' ')"
  [ "${n:-0}" -gt 0 ] && labels+=("dirty(${n})")

  n="$(git -C "${repo}" stash list 2>/dev/null | wc -l | tr -d ' ')"
  [ "${n:-0}" -gt 0 ] && labels+=("stash(${n})")

  n=0
  while IFS= read -r line; do
    case "${line}" in *ahead*) n=$((n + 1)) ;; esac
  done < <(git -C "${repo}" for-each-ref --format='%(push:track)' refs/heads/ 2>/dev/null)
  [ "${n}" -gt 0 ] && labels+=("ahead(${n})")

  n=0
  while IFS='|' read -r _name upstream; do
    [ -z "${upstream}" ] && n=$((n + 1))
  done < <(git -C "${repo}" for-each-ref --format='%(refname:short)|%(upstream)' refs/heads/ 2>/dev/null)
  [ "${n}" -gt 0 ] && labels+=("local-only(${n})")

  n="$(git -C "${repo}" worktree list 2>/dev/null | wc -l | tr -d ' ')"
  [ "${n:-0}" -gt 1 ] && labels+=("worktrees($((n - 1)))")

  if [ "${#labels[@]}" -eq 0 ]; then
    return 1
  fi
  (IFS=,; printf '%s' "${labels[*]}")
  return 0
}

scan_repo_issues() {
  section "Repos with work a fresh clone would lose"
  local root="${HOME}/workspaces"
  if [ ! -d "${root}" ]; then
    echo "  (no ~/workspaces)"
    return
  fi
  local any=0 g repo rel labels
  while IFS= read -r g; do
    repo="$(dirname "${g}")"
    if labels="$(repo_status_label "${repo}")"; then
      rel="${repo#"${HOME}"/}"
      printf '  %-50s  %s\n' "${rel}" "${labels}"
      any=1
    fi
  done < <(find "${root}" -maxdepth 4 -type d -name .git 2>/dev/null)
  if [ "${any}" -eq 0 ]; then
    echo "  (none — every repo is clean, pushed, and single-worktree)"
  fi
  return 0
}

